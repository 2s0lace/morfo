let currentLang = localStorage.getItem('morfo_lang') || 'pl';

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (lang === 'pl' || lang === 'en') {
    currentLang = lang;
    localStorage.setItem('morfo_lang', lang);
  }
}

export function t(key) {
  return STRINGS[currentLang][key] || STRINGS.pl[key] || key;
}
